// ─── Deep-merge helper (kz inherits en, overrides only what differs) ───────────
type DeepPartial<T> = { [K in keyof T]?: T[K] extends Record<string, unknown> ? DeepPartial<T[K]> : T[K] };

function createLocale(overrides: DeepPartial<TranslationKeys>): TranslationKeys {
  function merge<T>(base: T, over: DeepPartial<T>): T {
    if (typeof base !== "object" || base === null || Array.isArray(base)) {
      return (over !== undefined ? over : base) as T;
    }
    const result = { ...base } as T;
    for (const k in over) {
      const key = k as keyof T;
      result[key] = merge(base[key], (over as Record<string, unknown>)[k] as DeepPartial<T[keyof T]>);
    }
    return result;
  }
  return merge(en, overrides);
}

